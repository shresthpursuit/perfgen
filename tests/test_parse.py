def test_non_ascii_gap_message_can_be_printed_on_a_legacy_console(tmp_path, capsys):
    """A cp1252 console would otherwise raise UnicodeEncodeError and lose the whole report."""
    from perfgen.__main__ import main

    spec = WorkbookSpec()
    set_application_value(spec, "Application name", "Café commandes")
    set_application_value(spec, "Base URL", None)
    workbook = write_workbook(tmp_path / "spec.xlsx", spec)

    assert main(["parse", str(workbook), "--out", str(tmp_path / "ir")]) == 1
    assert "BLOCKING" in capsys.readouterr().out
