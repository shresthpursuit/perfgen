"""Workbook parsing.

Every workbook here is generated by `tests/fixtures/workbooks.py`. The tool is never run against a
real NFR spreadsheet while building (CLAUDE.md), and these fixtures are built to mirror the shipped
template's structure while making wrong answers visible: the `Example` column always differs from
the `Value` column, so a parser reading the wrong one fails rather than passing by coincidence.
"""

from __future__ import annotations

import pytest

from perfgen.ir.models import (
    AuthStrategy,
    AuthType,
    Method,
    ProfileId,
    Severity,
    SlaMetric,
    SlaUnit,
    ThroughputUnit,
)
from perfgen.parse import parse_workbook
from tests.fixtures.workbooks import (
    DEFAULT_APPLICATION,
    WorkbookSpec,
    blank_spec,
    drop_application_row,
    profile_row,
    set_application_value,
    write_workbook,
)


def parse(tmp_path, spec: WorkbookSpec | None = None):
    return parse_workbook(write_workbook(tmp_path / "spec.xlsx", spec))


def gap_for(result, field_path: str):
    return next((g for g in result.gaps if g.field == field_path), None)


